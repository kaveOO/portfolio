#!/usr/bin/env python3
"""Regenerate the landing page from the Claude Design export in design/.

Inputs (copied from the design project as-is):
  design/Lens Portfolio.dc.html, design/transitions.js, design/mobile-nav.js, design/scrollbar.js

Outputs (overwritten; edit the design, not these):
  src/pages/index.astro, src/styles/home.css,
  src/scripts/lens.js, src/scripts/transitions.js, src/scripts/mobile-nav.js, src/scripts/scrollbar.js

The Notes, Note, 404 and phone-preview pages are hand-ported and not touched here.
Run with: npm run sync:design
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESIGN = os.path.join(ROOT, 'design')


def read(name):
    with open(os.path.join(DESIGN, name), encoding='utf-8') as f:
        return f.read()


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', rel)


def replace_once(text, old, new, what):
    if text.count(old) != 1:
        sys.exit(f'sync-design: expected exactly one {what!r} in the design, found {text.count(old)}')
    return text.replace(old, new)


GENERATED = 'GENERATED by tools/sync-design.py from design/ - edit the design, not this file.'

src = read('Lens Portfolio.dc.html')

# --- head: the design's helmet scripts must match what layouts/Base.astro provides
helmet = src[src.index('<helmet>'):src.index('</helmet>')]
scripts = re.findall(r'<script(?: src="([^"]+)")?>([^<]*)</script>', helmet)
expected = [('', 'window.__abWait = 1;'), ('transitions.js', ''), ('mobile-nav.js', '')]
if scripts != expected:
    print('sync-design: WARNING the design head scripts changed; update src/layouts/Base.astro to match:', scripts)

# --- css: the helmet stylesheet, plus classes standing in for style-hover / style-focus
a = src.index('<style>', src.index('<helmet>')) + len('<style>\n')
css = src[a:src.index('</style>', a)]
css = replace_once(css, 'a:hover{color:var(--accent,#6e95ff);}\n',
                   'a:hover{color:var(--accent,#6e95ff);}\n.dim:hover{opacity:0.6;}\n.skip:focus{top:12px !important;}\n',
                   'a:hover rule')
write('src/styles/home.css', f'/* {GENERATED} */\n' + css)

# --- body markup
body = src[src.index('<div ref="{{ rootRef }}"'):src.index('</x-dc>')].rstrip()
for old, new in [('ref="{{ rootRef }}"', 'data-root=""'),
                 (' style-hover="opacity:0.6"', ' class="dim"'),
                 (' style-focus="top:12px"', ' class="skip"')]:
    body = body.replace(old, new)
# Braces are Astro expressions; keep any literal ones as text. Expressions are added after this.
body = re.sub(r'[{}]', lambda m: "{'%s'}" % m.group(0), body)
body = body.replace('href="Notes.dc.html"', "href={url('/notes/')}")
if 'style-' in body or '.dc.html' in body:
    sys.exit('sync-design: the design uses an attribute or link this script does not convert yet')

# Notes rows: the design has three hand-written rows; render the three latest notes instead.
row_re = re.compile(r'<div data-essay=[\s\S]*?\n</div>\n</div>\n<div data-lens="" style="height:1px;[^"]*"></div>')
rows = row_re.findall(body)
if len(rows) < 1:
    sys.exit('sync-design: could not find the Notes rows (data-essay) in the design')
tpl = rows[0]
num = re.search(r'>(\d\d)</span>', tpl).group(1)
title = re.search(r'<div data-ewrap[^>]*><span[^>]*>([^<]+)</span>', tpl).group(1)
meta = re.search(r'<span[^>]*>([^<]+)</span>\n</div>\n</div>\n<div data-lens', tpl).group(1)
tpl = replace_once(tpl, f'>{num}</span>', '>{pad(i + 1)}</span>', 'row number')
tpl = replace_once(tpl, f'>{title}</span>', '>{n.data.title}</span>', 'row title')
tpl = replace_once(tpl, f'>{meta}</span>', '>{monthYear(n.data.date)} · {n.data.tag} · {readingMinutes(n)} min</span>', 'row meta')
tpl = replace_once(tpl, '<div data-essay=""', '<div data-essay="" data-href={noteUrl(n)}', 'row element')
start = body.index(rows[0])
end = body.index(rows[-1]) + len(rows[-1])
body = body[:start] + '{latest.map((n, i) => (\n<Fragment>\n' + tpl + '\n</Fragment>\n))}' + body[end:]

page = f'''---
// {GENERATED}
import Base from '../layouts/Base.astro';
import {{ getNotes, noteUrl, monthYear, readingMinutes }} from '../lib/notes';
import {{ url }} from '../lib/paths';
import '../styles/home.css';

const latest = (await getNotes()).slice(0, 3);
const pad = (n: number) => String(n).padStart(2, '0');
---
<Base
  title="Alban Billiette — Game security and full-stack developer"
  description="Systems programmer and student at 42 Warsaw, working on game security and full-stack development: anti-cheat reverse engineering, Windows kernel drivers and full-stack products."
  waitForReady
  scrollbar={{false}}
>
{body}
<script src="../scripts/lens.js"></script>
</Base>
'''
write('src/pages/index.astro', page)

# --- js/lens.js: the design component as a plain class
a = src.index('class Component extends DCLogic {')
js = src[a:src.index('</script>', a)].rstrip()
for old, new in [
    ('class Component extends DCLogic {\n  rootRef = React.createRef();\n',
     'class Lens {\n  constructor(root, props) { this.rootEl = root; this.props = props; }\n\n'),
    ('  renderVals() { return { rootRef: this.rootRef }; }\n\n', ''),
    ('componentDidMount() {\n    const root = this.rootRef.current;', 'mount() {\n    const root = this.rootEl;'),
    ('componentDidUpdate(prev) {\n    if (prev.theme !== this.props.theme) {',
     'setTheme(theme) {\n    if (theme !== this.props.theme) { this.props = { ...this.props, theme };'),
    ('componentWillUnmount() {', 'destroy() {'),
]:
    js = replace_once(js, old, new, old.split('\n')[0])
# Notes rows open their own note (data-href) instead of the design's single sample page.
js = js.replace("'Note.dc.html'", 'el.dataset.href').replace('Component.', 'Lens.')
if 'Component' in js or 'React' in js or '.dc.html' in js:
    sys.exit('sync-design: the design script references something this script does not convert yet')
props = re.search(r'data-props="([^"]*)"', src)
inertia = 0.7
if props:
    m = re.search(r'inertia&quot;:\{[^}]*?default&quot;:([\d.]+)', props.group(1))
    if m:
        inertia = float(m.group(1))
lens = f'''// {GENERATED}
// Glass-lens portfolio: smooth-scrolled content mirrored into a canvas texture
// and refracted through a WebGL lens whose shape morphs per section.

{js}

const root = document.querySelector('[data-root]');
if (root) {{
  const lens = new Lens(root, {{ theme: 'dark', refraction: 1, aberration: 1, inertia: {inertia} }});
  lens.mount();
  window.lens = lens;
}}
'''
write('src/scripts/lens.js', lens)

# --- shared head scripts
trans = read('transitions.js')
old = r'/\.dc\.html$/.test(u.pathname)'
if old not in trans:
    sys.exit('sync-design: transitions.js no longer matches pages by ".dc.html"; update this script')
# Site pages are routes like /, /notes/ and /notes/<slug>/ (or .html files): no file extension.
write('src/scripts/transitions.js', f'// {GENERATED}\n' + trans.replace(old, r'/(\/|\.html|\/[^.\/]*)$/.test(u.pathname)'))
for name in ('mobile-nav.js', 'scrollbar.js'):
    text = read(name)
    if '.dc.html' in text:
        sys.exit(f'sync-design: {name} references .dc.html pages; update this script')
    write(f'src/scripts/{name}', f'// {GENERATED}\n' + text)
